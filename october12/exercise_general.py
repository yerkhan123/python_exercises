#28. Деление на ноль. a / b в try, при ZeroDivisionError — «На ноль делить нельзя».
try:
    a = float(input("Первое число: "))
    b = float(input("Второе число: "))
    print(a / b)
except ZeroDivisionError:
    print("На ноль делить нельзя")
except ValueError:
    print("Ошибка ввода")

