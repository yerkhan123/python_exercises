"""
7. Имена и оценки
(zip, list, for)

names = ["Аня", "Борис", "Вера"]
grades = [5, 3, 4]

Выведи:

Аня - 5
Борис - 3
Вера - 4

Потом создай dict(zip(names, grades)) и выведи его.
"""
names = ["Аня", "Борис", "Вера"]
grades = [5, 3, 4]

for name, grade in zip(names, grades):
    print(f"{name} - {grade}")

students = dict(zip(names, grades))

print(students)
