"""
8. Безопасный калькулятор
создай калькулятор для следующих операций + - / *.
Принимает с консоли через input() 2 целых числа. Необходимо обеспечить обработку возможных исключений при операциях int() и делении на ноль
"""
try:
    a = int(input("Введите первое число: "))
    b = int(input("Введите второе число: "))

    operation = input("Введите операцию (+, -, *, /): ")

    if operation == "+":
        print(a + b)
    elif operation == "-":
        print(a - b)
    elif operation == "*":
        print(a * b)
    elif operation == "/":
        print(a / b)
    else:
        print("Неизвестная операция")

except ValueError:
    print("Ошибка: нужно вводить целые числа")

except ZeroDivisionError:
    print("Ошибка: на ноль делить нельзя")
